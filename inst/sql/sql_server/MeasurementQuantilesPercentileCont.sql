-- The same quantile table as MeasurementQuantiles.sql, computed with PERCENTILE_CONT.
--
-- Selected by preprocessing.quantileMethod = "percentileCont". It is the
-- shorter query, and SQL Server's PERCENTILE_CONT uses the same (n - 1) * p
-- linear interpolation as pandas, so the values agree. Two caveats, which is
-- why "rank" is the default:
--
--   * SqlRender v1.9.0 passes PERCENTILE_CONT through untranslated. It happens
--     to be valid PostgreSQL and Oracle too, but not on every dialect.
--   * SQL Server requires the probability to be a literal, so the eleven calls
--     are generated by R/MeasurementQuantiles.R rather than joined in.
--
-- The grouping is (measurement_concept_id, unit_concept_id), as in
-- MeasurementQuantiles.sql, so one FeatureExtraction covariate_id
-- resolves to exactly one row.
--
-- @restrict_person_table limits which patients the values come from.

{DEFAULT @restrict_person_table = ''}

SELECT H.measurement_concept_id,
       H.unit_concept_id,
       H.value_number
INTO #quantile_source
FROM @measurements_table H
WHERE H.is_numeric = 1
{@restrict_person_table != ''} ? {  AND EXISTS (SELECT 1 FROM @restrict_person_table RP WHERE RP.person_id = H.person_id)}
;

IF OBJECT_ID('@meas_quantiles_table', 'U') IS NOT NULL DROP TABLE @meas_quantiles_table;

CREATE TABLE @meas_quantiles_table (
  measurement_concept_id BIGINT NOT NULL,
  unit_concept_id BIGINT NOT NULL,
  unit_source_value VARCHAR(50) NULL,
  n_unit_source_value INT NULL,
@quantile_column_definitions
  n BIGINT NOT NULL,
  basis VARCHAR(10) NOT NULL
);

INSERT INTO @meas_quantiles_table (measurement_concept_id, unit_concept_id, unit_source_value, n_unit_source_value, @quantile_column_names, n, basis)
SELECT DISTINCT
       S.measurement_concept_id,
       S.unit_concept_id,
       CU.unit_source_value,
       CU.n_unit_source_value,
@percentile_expressions
       COUNT(*) OVER (
         PARTITION BY S.measurement_concept_id, S.unit_concept_id
       ) AS n,
       '@quantile_basis' AS basis
FROM #quantile_source S
INNER JOIN @concept_unit_table CU
  ON S.measurement_concept_id = CU.measurement_concept_id
  AND S.unit_concept_id = CU.unit_concept_id;

TRUNCATE TABLE #quantile_source;
DROP TABLE #quantile_source;
